-- Creates All in One Edition's missing community tables and secures public video uploads.
create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text unique not null check (char_length(btrim(username)) between 1 and 24),
  avatar_url text check (avatar_url is null or char_length(avatar_url) <= 500),
  created_at timestamptz not null default now()
);
create table if not exists public.friend_requests (
  id bigint generated by default as identity primary key,
  requester uuid not null references auth.users(id) on delete cascade,
  addressee uuid not null references auth.users(id) on delete cascade,
  status text not null default 'pending' check (status in ('pending','accepted','declined')),
  created_at timestamptz not null default now(), unique(requester,addressee), check(requester<>addressee)
);
create table if not exists public.direct_messages (
  id bigint generated by default as identity primary key,
  sender_id uuid not null references auth.users(id) on delete cascade,
  recipient_id uuid not null references auth.users(id) on delete cascade,
  body text not null check(char_length(btrim(body)) between 1 and 2000),
  created_at timestamptz not null default now(), check(sender_id<>recipient_id)
);
create table if not exists public.parties (
  id uuid primary key default gen_random_uuid(), code text unique not null,
  owner_id uuid not null references auth.users(id) on delete cascade, created_at timestamptz not null default now()
);
create table if not exists public.party_members (
  party_id uuid not null references public.parties(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  joined_at timestamptz not null default now(), primary key(party_id,user_id)
);
create table if not exists public.meeting_rooms (
  id uuid primary key default gen_random_uuid(),
  party_id uuid not null references public.parties(id) on delete cascade,
  created_by uuid not null references auth.users(id) on delete cascade, created_at timestamptz not null default now()
);
create table if not exists public.social_posts (
  id uuid primary key default gen_random_uuid(), visitor_id text not null, username text not null,
  avatar_url text, caption text not null default '', media_type text not null check(media_type in ('image','video')),
  media_url text not null, created_at timestamptz not null default now(),
  check(char_length(btrim(visitor_id)) between 20 and 100), check(char_length(btrim(username)) between 1 and 32),
  check(char_length(caption)<=500), check(char_length(media_url)<=4000)
);
create table if not exists public.social_comments (
  id bigint generated by default as identity primary key,
  post_id uuid not null references public.social_posts(id) on delete cascade,
  visitor_id text not null, username text not null, body text not null, created_at timestamptz not null default now(),
  check(char_length(btrim(visitor_id)) between 20 and 100), check(char_length(btrim(username)) between 1 and 32),
  check(char_length(btrim(body)) between 1 and 300)
);
create table if not exists public.social_reactions (
  post_id uuid not null references public.social_posts(id) on delete cascade, visitor_id text not null,
  created_at timestamptz not null default now(), primary key(post_id,visitor_id),
  check(char_length(btrim(visitor_id)) between 20 and 100)
);
create table if not exists public.social_follows (
  visitor_id text not null, username text not null, created_at timestamptz not null default now(),
  primary key(visitor_id,username), check(char_length(btrim(visitor_id)) between 20 and 100),
  check(char_length(btrim(username)) between 1 and 32)
);
create index if not exists social_posts_created_at_idx on public.social_posts(created_at desc);
create index if not exists social_posts_visitor_idx on public.social_posts(visitor_id);
create index if not exists social_comments_post_idx on public.social_comments(post_id,created_at asc);
create index if not exists direct_messages_pair_time_idx on public.direct_messages(sender_id,recipient_id,created_at desc);

