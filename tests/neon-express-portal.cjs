'use strict';
const fs=require('node:fs'),assert=require('node:assert/strict'),path=require('node:path');
const root=path.resolve(__dirname,'..');
const out=path.join(root,'dist','neon-express-portal');
const html=fs.readFileSync(path.join(out,'index.html'),'utf8');
const js=fs.readFileSync(path.join(out,'game.js'),'utf8');
const license=fs.readFileSync(path.join(out,'THIRD_PARTY_NOTICES.txt'),'utf8');
const readme=fs.readFileSync(path.join(out,'README.txt'),'utf8');
assert.match(html,/<title>NEON EXPRESS/);
assert.match(html,/src="\.\/game\.js"/);
assert.match(html,/id="start"/);
assert.match(html,/id="scene"/);
assert.match(html,/id="right"/);
assert.match(html,/id="left"/);
assert.match(html,/aria-label="Game progress"/);
assert.doesNotMatch(html,/src=["']\/games\/neon-express|href="\/browser-games"/);
assert.doesNotMatch(html,/https:\/\/cdn\.jsdelivr\.net|pagead2\.googlesyndication\.com|adsbygoogle|\/_vercel\/insights|<script[^>]*src=["']https?:/i);
assert.ok(js.length>120000,'Engine and code should be bundled, not loaded remotely');
assert.match(js,/WebGL/,'Bundled 3D engine should be present');
assert.doesNotMatch(js,/from\s*['"]three['"]|import\(\s*['"]three['"]\s*\)/,'No npm bare import can remain in standalone game');
assert.match(license,/MIT License/i);
assert.match(license,/three\.js/i);
assert.match(readme,/NOT a portal-approved game/);
assert.match(readme,/Eligible adult\/guardian/);
console.log('Portal 3D build passed: self-contained renderer, local scripts, no separate ad tags or analytics, full MIT license.');
